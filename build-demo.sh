#!/usr/bin/env bash
# Builds frontend/js/demo/backend-bundle.js from the Apps Script sources so Demo Mode (and tests)
# always run the exact backend code. Re-run after editing any backend/*.gs file.
set -e
cd "$(dirname "$0")"
OUT=frontend/js/demo/backend-bundle.js
{
  echo "/* AUTO-GENERATED by build-demo.sh — concatenation of backend/*.gs for Demo Mode. Do not edit. */"
  for f in Config Utils Database Validation Auth DesignationService EmployeeService QuestionnaireService TimeTrackingService TaskService MisService DifficultyService ReportService WhatsAppService AnalyticsService NotificationService SampleData Code; do
    echo "// ===== backend/$f.gs ====="; cat "backend/$f.gs"; echo
  done
  echo "CONFIG.DEMO_MODE = true;"
} > "$OUT"
node --check "$OUT" && echo "Built $OUT ($(wc -c < "$OUT") bytes)"
